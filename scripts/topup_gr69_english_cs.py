def build_questions():
    qs = []
    def add(lst, subject, grade, difficulty):
        for q in lst:
            qs.append(dict(subject=subject,grade=grade,difficulty=difficulty,
                           topic=q["topic"],subTopic=q["subTopic"],
                           questionText=q["questionText"],options=q["options"],
                           correctAnswer=q["correct"],explanation=q["explanation"]))
    add(ENG6_OLY, "English", 6, "Olympiad")
    add(ENG9_OLY, "English", 9, "Olympiad")
    add(CS9_OLY,  "Computer Science", 9, "Olympiad")
    add(CS6_OLY,  "Computer Science", 6, "Olympiad")
    return qs

def main():
    conn = pyodbc.connect(DB_CONN)
    questions = build_questions()
    ok = dup = err = 0
    for i, q in enumerate(questions, 1):
        try:
            res = insert(conn, q)
        except Exception as e:
            res = f"ERR: {e}"
        m = "✓" if res=="OK" else ("~" if res=="DUP" else "✗")
        print(f"  {m} Q{i:03d} [{q['subject']} G{q['grade']} {q['difficulty']}] {q['subTopic'][:50]} → {res}")
        if res=="OK": ok+=1
        elif res=="DUP": dup+=1
        else: err+=1
    conn.close()
    print(f"\n  Done: {ok} posted, {dup} duplicates, {err} errors  (total={ok+dup+err})")

if __name__ == "__main__":
    main()
